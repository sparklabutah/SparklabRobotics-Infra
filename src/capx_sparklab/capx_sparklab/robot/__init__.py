"""The YAM-Ultra with i2rt's stock LINEAR_4310 gripper, as cuRobo and GraspGenX see it.

Generated by ``capx_sparklab.robot.build``; this module only reads the result.
"""

from __future__ import annotations

import hashlib
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
import yaml

HERE = Path(__file__).resolve().parent
URDF = HERE / "yam.urdf"
CUROBO_CONFIG = HERE / "curobo_yam.yml"
GRASPGENX_ROOT = HERE / "graspgenx"
GRASPGENX_GRIPPER = "sparklab_yam"

TOOL_FRAME = "grasp_base"
# Grasp centre along TOOL_FRAME z: the stock grasp site, sparklab_yam's tool0.
TOOL0_DEPTH = 0.1347
# Driver gripper command 1 = open, 0 = closed; GraspGenX's stock jaw stroke, 2 x 0.047.
GRIPPER_OPENING = 0.094
# The URDF's finger joints: 0 is closed (the tips meet), this is fully open.
FINGER_OPEN = -0.04695
# The fingertips, 1 cm past the grasp centre along TOOL_FRAME z (GraspGenX's yam_gripper bbox).
FINGERTIP_DEPTH = TOOL0_DEPTH + 0.01


def placed_urdf(base_in_world: np.ndarray) -> Path:
    """The arm's URDF with its world joint set to base_in_world (4x4), and absolute mesh paths.

    Returns: a file in the temp directory, one per placement.
    """
    from scipy.spatial.transform import Rotation

    root = ET.parse(URDF).getroot()
    origin = root.find("joint[@name='world_joint']/origin")
    origin.set("xyz", " ".join(f"{v:.6f}" for v in base_in_world[:3, 3]))
    origin.set("rpy", " ".join(
        f"{v:.9f}" for v in Rotation.from_matrix(base_in_world[:3, :3]).as_euler("xyz")))
    for mesh in root.iter("mesh"):
        mesh.set("filename", str(HERE / mesh.get("filename")))
    text = ET.tostring(root, encoding="unicode")
    placed = Path(tempfile.gettempdir()) / f"yam_{hashlib.sha1(text.encode()).hexdigest()[:12]}.urdf"
    placed.write_text(text)
    return placed


def curobo_config(base_in_world: np.ndarray) -> dict:
    """The cuRobo robot config for one arm whose base sits at base_in_world.

    Both arms plan in one world frame: the arm's URDF gets its world joint set
    to this placement, so everything the planners exchange is in that frame.
    base_in_world: 4x4.
    Returns: a robot config dict for Planner(robot=...).
    """
    config = yaml.safe_load(CUROBO_CONFIG.read_text())
    config["kinematics"]["urdf_path"] = str(placed_urdf(base_in_world))
    config["kinematics"]["asset_root_path"] = str(HERE)
    return config
